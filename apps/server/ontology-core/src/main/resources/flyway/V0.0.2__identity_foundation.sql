-- 身份与项目成员关系基础结构。旧项目不在迁移阶段自动分配所有者。
ALTER TABLE ontology.og_organization
    ADD COLUMN bootstrap_key VARCHAR(120);
CREATE UNIQUE INDEX uk_og_organization_bootstrap_key
    ON ontology.og_organization(bootstrap_key)
    WHERE bootstrap_key IS NOT NULL;

CREATE TABLE ontology.og_user (
    id VARCHAR(36) PRIMARY KEY,
    username VARCHAR(120) NOT NULL UNIQUE,
    display_name VARCHAR(200) NOT NULL,
    system_admin BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    auth_version BIGINT NOT NULL DEFAULT 0 CHECK (auth_version >= 0),
    create_time TIMESTAMP NOT NULL DEFAULT NOW(),
    update_time TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE ontology.og_password_credential (
    user_id VARCHAR(36) PRIMARY KEY REFERENCES ontology.og_user(id) ON DELETE CASCADE,
    password_hash VARCHAR(512) NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT NOW(),
    update_time TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE ontology.og_external_identity (
    issuer VARCHAR(500) NOT NULL,
    subject VARCHAR(500) NOT NULL,
    user_id VARCHAR(36) NOT NULL REFERENCES ontology.og_user(id) ON DELETE CASCADE,
    create_time TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (issuer, subject)
);
CREATE INDEX idx_og_external_identity_user ON ontology.og_external_identity(user_id);

CREATE TABLE ontology.og_project_member (
    project_id BIGINT NOT NULL REFERENCES ontology.og_organization(id) ON DELETE CASCADE,
    user_id VARCHAR(36) NOT NULL REFERENCES ontology.og_user(id) ON DELETE CASCADE,
    role VARCHAR(16) NOT NULL CHECK (role IN ('OWNER', 'ADMIN', 'EDITOR', 'VIEWER')),
    create_time TIMESTAMP NOT NULL DEFAULT NOW(),
    update_time TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (project_id, user_id)
);
CREATE INDEX idx_og_project_member_user ON ontology.og_project_member(user_id);
CREATE UNIQUE INDEX uk_og_project_member_single_owner
    ON ontology.og_project_member(project_id)
    WHERE role = 'OWNER';

CREATE TABLE ontology.og_bootstrap_run (
    seed_key VARCHAR(120) PRIMARY KEY,
    input_digest CHAR(64) NOT NULL,
    completed_at TIMESTAMP NOT NULL,
    details_json JSONB NOT NULL DEFAULT '{}'::JSONB
);

CREATE TABLE ontology.og_audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(120) NOT NULL,
    actor_user_id VARCHAR(36) REFERENCES ontology.og_user(id) ON DELETE SET NULL,
    details_json JSONB NOT NULL DEFAULT '{}'::JSONB,
    create_time TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_og_audit_event_created ON ontology.og_audit_event(create_time);

-- Spring Session JDBC 默认 PostgreSQL 表结构，限定在 ontology schema。
CREATE TABLE ontology.spring_session (
    primary_id CHAR(36) NOT NULL PRIMARY KEY,
    session_id CHAR(36) NOT NULL UNIQUE,
    creation_time BIGINT NOT NULL,
    last_access_time BIGINT NOT NULL,
    max_inactive_interval INT NOT NULL,
    expiry_time BIGINT NOT NULL,
    principal_name VARCHAR(100)
);
CREATE INDEX idx_spring_session_expiry ON ontology.spring_session(expiry_time);
CREATE INDEX idx_spring_session_principal ON ontology.spring_session(principal_name);

CREATE TABLE ontology.spring_session_attributes (
    session_primary_id CHAR(36) NOT NULL REFERENCES ontology.spring_session(primary_id) ON DELETE CASCADE,
    attribute_name VARCHAR(200) NOT NULL,
    attribute_bytes BYTEA NOT NULL,
    PRIMARY KEY (session_primary_id, attribute_name)
);
